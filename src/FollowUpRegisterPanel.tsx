import { Fragment, useDeferredValue, useEffect, useMemo, useState } from "react";
import { ClipboardList, Download, ExternalLink, FileText, MessageCircle, Plus, RefreshCw, Search, Trash2, Users } from "lucide-react";
import { calculateMonthlyInterest, calculateGiftAmount, formatINR, parseDealNumber, dealTransactionTypes, loanDirections, getTransactionAmount } from "./lib/deal-structure";

export type FollowUpRegisterItem = {
  id: string;
  person: string;
  role: string;
  linkedRecordId: string;
  description: string;
  amount: string;
  promisedDate: string;
  promisedTime: string;
  responseType: string;
  status: string;
  notes: string;
  isPrimary: boolean;
  autoGenerated?: boolean;
  createdAt: string;
  updatedAt: string;
};
type ContactRow = {
  id: string; name: string; phone: string; role: string; roles?: string[];
  email?: string; whatsappGroupIds?: string[]; followUps?: FollowUpRegisterItem[];
};
type RecordRow = {
  id: string; title: string; module: string; value: string; status: string;
  contact: string; primaryContactId?: string; followUpContactId?: string;
  nextFollowUpDate?: string; nextFollowUpTime?: string; nextResponseDate?: string; nextResponseTime?: string;
  nextResponseDescription?: string; nextAction?: string; notes?: string;
  moduleData: Record<string,string>;
};
type GroupRow = { id: string; name: string; jid?: string; size?: number };
type DraftRow = { contactId: string; item: FollowUpRegisterItem; isNew: boolean; dirty?: boolean };
type Props = {
  contacts: ContactRow[];
  properties: RecordRow[];
  groups: GroupRow[];
  readOnly?: boolean;
  onUpdateFollowUps: (contactId: string, rows: FollowUpRegisterItem[]) => void;
  onOpenContact360: (contactId: string) => void;
  onAddModule: (contactId: string) => void;
  onEditRecord: (record: RecordRow) => void;
  onDownloadRecord: (record: RecordRow) => void;
  onExportPdf: () => void;
};

const statuses = ["Awaiting response", "Reached back", "Completed", "Overdue", "On hold", "Cancelled"];
const channels = ["Call", "WhatsApp", "Email", "Meeting", "Site visit", "Document", "Payment update", "Other"];
const rowKey = (contactId: string, rowId: string) => contactId + "::" + rowId;
const emptyRows = (contacts: ContactRow[]): Record<string,DraftRow> => Object.fromEntries(
  contacts.flatMap(contact => (contact.followUps || []).map(item => [
    rowKey(contact.id,item.id), { contactId: contact.id, item: { ...item, amount: String(item.amount ?? "") }, isNew: false, dirty: false }
  ]))
);
const contactLinksRecord = (contact: ContactRow, record: RecordRow) => {
  const data = record.moduleData || {};
  const linkedIds = [
    record.followUpContactId || "",
    record.primaryContactId || "",
    ...(data.__linkedContactIds || "").split(","),
    ...Object.entries(data).filter(([key,value]) => key.startsWith("__contact_") && Boolean(value)).map(([,value]) => String(value))
  ].filter(Boolean);
  return linkedIds.includes(contact.id) || (record.contact || "").trim().toLocaleLowerCase() === contact.name.trim().toLocaleLowerCase();
};
const createFollowUp = (contact: ContactRow): FollowUpRegisterItem => {
  const now = new Date().toISOString();
  return {
    id: "contact-followup-" + Date.now() + "-" + Math.random().toString(36).slice(2,8),
    person: contact.name, role: contact.role || contact.roles?.[0] || "Client",
    linkedRecordId: "", description: "", amount: "", promisedDate: "", promisedTime: "",
    responseType: "Call", status: "Awaiting response", notes: "", isPrimary: false,
    createdAt: now, updatedAt: now
  };
};
export default function FollowUpRegisterPanel(props: Props) {
  const [drafts,setDrafts] = useState<Record<string,DraftRow>>(() => emptyRows(props.contacts));
  const [query,setQuery] = useState("");
  const [statusFilter,setStatusFilter] = useState("All statuses");
  const [moduleFilter,setModuleFilter] = useState("All modules");
  const [roleFilters,setRoleFilters] = useState<string[]>([]);
  const [groupFilters,setGroupFilters] = useState<string[]>([]);
  const [transactionFilter,setTransactionFilter] = useState("All transaction types");
  const [loanDirectionFilter,setLoanDirectionFilter] = useState("All loan directions");
  const [addContactId,setAddContactId] = useState(props.contacts[0]?.id || "");
  const [addContactSearch,setAddContactSearch] = useState("");
  const [addContactPickerOpen,setAddContactPickerOpen] = useState(false);
  const deferredQuery = useDeferredValue(query);
  const deferredAddContactSearch = useDeferredValue(addContactSearch);
  const matchingAddContacts = useMemo(() => { const term=deferredAddContactSearch.trim().normalize("NFKC").toLocaleLowerCase(); return props.contacts.filter(contact=>!term||[contact.name,contact.role,...(contact.roles||[]),contact.phone,contact.email].filter(Boolean).join(" ").normalize("NFKC").toLocaleLowerCase().includes(term)).sort((a,b)=>a.name.localeCompare(b.name)).slice(0,30); },[props.contacts,deferredAddContactSearch]);

  useEffect(() => {
    const saved = emptyRows(props.contacts);
    setDrafts(current => {
      const next = { ...current };
      for (const [key,row] of Object.entries(current)) {
        if (saved[key]) {
          if (!row.dirty) next[key] = saved[key];
        } else if (!row.isNew && !row.dirty) {
          delete next[key];
        }
      }
      for (const [key,row] of Object.entries(saved)) if (!next[key]) next[key] = row;
      return next;
    });
  },[props.contacts]);
  useEffect(() => {
    if (!props.contacts.some(contact => contact.id === addContactId)) setAddContactId("");
  },[props.contacts,addContactId]);

  const contactIndex = useMemo(() => new Map(props.contacts.map(contact => [contact.id,contact])),[props.contacts]);
  const recordIndex = useMemo(() => new Map(props.properties.map(record => [record.id,record])),[props.properties]);
  const rows = useMemo(() => Object.entries(drafts).flatMap(([key,draft]) => {
    const contact = contactIndex.get(draft.contactId);
    if (!contact) return [];
    const record = recordIndex.get(draft.item.linkedRecordId);
    const linkedGroups = new Set([
      ...(contact.whatsappGroupIds || []),
      ...props.properties.filter(item => contactLinksRecord(contact,item))
        .flatMap(item => (item.moduleData?.__linkedWhatsAppGroupIds || "").split(",").filter(Boolean))
    ]);
    const groupNames = props.groups.filter(group => linkedGroups.has(group.id)).map(group => group.name);
    const linkedRecords = props.properties.filter(item => contactLinksRecord(contact,item));
    const searchText = [
      contact.name,contact.phone,contact.role,...(contact.roles || []),draft.item.person,draft.item.role,
      draft.item.description,draft.item.amount,draft.item.promisedDate,draft.item.promisedTime,
      draft.item.responseType,draft.item.status,draft.item.notes,record?.module,record?.title,
      ...Object.entries(record?.moduleData||{}).flatMap(([key,value])=>[key,String(value??"")]),
      ...groupNames
    ].filter(Boolean).join(" ").normalize("NFKC").toLocaleLowerCase();
    const transactionType=record?.moduleData?.__transactionType||"Not decided";
    const loanDirection=record?.moduleData?.__loanDirection||"";
    const monthlyInterest=transactionType==="Loan"?calculateMonthlyInterest(record?.moduleData,parseDealNumber(record?.value)):0;
    return [{key,contact,item:draft.item,record,linkedRecords,groupNames,groupIds:Array.from(linkedGroups),searchText,transactionType,loanDirection,monthlyInterest}];
  }).sort((a,b) => {
    const byDate = (a.item.promisedDate || "9999-12-31").localeCompare(b.item.promisedDate || "9999-12-31");
    return byDate || a.contact.name.localeCompare(b.contact.name) || a.item.person.localeCompare(b.item.person);
  }),[drafts,contactIndex,recordIndex,props.properties,props.groups]);
  const visibleRows = useMemo(() => {
    const term = deferredQuery.trim().normalize("NFKC").toLocaleLowerCase();
    return rows.filter(row =>
      (!term || row.searchText.includes(term)) &&
      (statusFilter === "All statuses" || row.item.status === statusFilter) &&
      (moduleFilter === "All modules" || (row.record?.module || "Contact-level") === moduleFilter) &&
      (transactionFilter === "All transaction types" || row.transactionType === transactionFilter) &&
      (loanDirectionFilter === "All loan directions" || (row.transactionType === "Loan" && row.loanDirection === loanDirectionFilter)) &&
      (!roleFilters.length || roleFilters.some(role => [row.item.role,row.contact.role,...(row.contact.roles||[])].filter(Boolean).includes(role))) &&
      (!groupFilters.length || groupFilters.some(groupId => row.groupIds.includes(groupId)))
    );
  },[rows,deferredQuery,statusFilter,moduleFilter,transactionFilter,loanDirectionFilter,roleFilters,groupFilters]);
  const visibleByContact = useMemo(() => {
    const grouped = new Map<string,typeof visibleRows>();
    for (const row of visibleRows) grouped.set(row.contact.id,[...(grouped.get(row.contact.id)||[]),row]);
    return grouped;
  },[visibleRows]);
  const moduleOptions = useMemo(() => Array.from(new Set(rows.map(row=>row.record?.module || "Contact-level"))).sort(),[rows]);
  const roleOptions = useMemo(() => Array.from(new Set(rows.flatMap(row=>[row.item.role,row.contact.role,...(row.contact.roles||[])].filter((value): value is string => Boolean(value))))).sort(),[rows]);
  const groupOptions = useMemo(() => props.groups.filter(group=>rows.some(row=>row.groupIds.includes(group.id))),[props.groups,rows]);
  const transactionOptions = useMemo(() => dealTransactionTypes.filter(type=>rows.some(row=>row.transactionType===type)),[rows]);
  const loanPrimaryRows = rows.filter(row=>row.transactionType==="Loan"&&row.item.isPrimary&&row.record);
  const monthlyInterestReceivable = loanPrimaryRows.filter(row=>row.loanDirection===loanDirections[0]).reduce((sum,row)=>sum+row.monthlyInterest,0);
  const monthlyInterestPayable = loanPrimaryRows.filter(row=>row.loanDirection===loanDirections[1]).reduce((sum,row)=>sum+row.monthlyInterest,0);
  const overdueCount = rows.filter(row => row.item.promisedDate && row.item.promisedDate < new Date().toISOString().slice(0,10) && !["Completed","Cancelled","Reached back"].includes(row.item.status)).length;
  const primaryCount = rows.filter(row=>row.item.isPrimary).length;

  const patch = (key:string, field:keyof FollowUpRegisterItem, value:string|boolean) => {
    setDrafts(current => {
      const row = current[key];
      return row ? {...current,[key]:{...row,item:{...row.item,[field]:value},dirty:true}} : current;
    });
  };
  const chooseRecord = (key:string,recordId:string) => {
    setDrafts(current => {
      const draft = current[key];
      if (!draft) return current;
      const record = props.properties.find(item=>item.id===recordId);
      const contact = contactIndex.get(draft.contactId);
      const hasPrimary = Object.entries(current).some(([otherKey,row]) =>
        otherKey!==key && row.contactId===draft.contactId && row.item.linkedRecordId===recordId && row.item.isPrimary
      );
      return {...current,[key]:{...draft,item:{
        ...draft.item,linkedRecordId:recordId,
        amount:record?(draft.item.amount||record.value||""):draft.item.amount,
        description:record?(draft.item.description||""):draft.item.description,
        promisedDate:record?(draft.item.promisedDate||""):draft.item.promisedDate,
        promisedTime:record?(draft.item.promisedTime||""):draft.item.promisedTime,
        isPrimary:Boolean(record&&contact&&!hasPrimary)
      },dirty:true}};
    });
  };
  const setPrimary = (key:string,checked:boolean) => {
    const target = drafts[key];
    setDrafts(current => Object.fromEntries(Object.entries(current).map(([otherKey,draft]) => [
      otherKey,
      otherKey===key
        ? {...draft,item:{...draft.item,isPrimary:checked},dirty:true}
        : checked && target?.contactId===draft.contactId && target.item.linkedRecordId && target.item.linkedRecordId===draft.item.linkedRecordId
          ? {...draft,item:{...draft.item,isPrimary:false},dirty:true}
          : draft
    ])));
  };
  const addForContact = (contactId:string) => {
    const contact = contactIndex.get(contactId);
    if (!contact) return;
    const item = createFollowUp(contact);
    setDrafts(current=>({...current,[rowKey(contactId,item.id)]:{contactId,item,isNew:true,dirty:true}}));
  };
  const save = (key:string) => {
    const draft = drafts[key];
    const contact = draft && contactIndex.get(draft.contactId);
    if (!draft || !contact || props.readOnly) return;
    const saved = {...draft.item,amount:String(draft.item.amount??""),updatedAt:new Date().toISOString()};
    const previous = contact.followUps || [];
    const next = previous.some(item=>item.id===saved.id)
      ? previous.map(item=>item.id===saved.id?saved:item)
      : [...previous,saved];
    props.onUpdateFollowUps(contact.id,next);
    setDrafts(current=>({...current,[key]:{contactId:contact.id,item:saved,isNew:false,dirty:false}}));
  };
  const remove = (key:string) => {
    const draft = drafts[key];
    const contact = draft && contactIndex.get(draft.contactId);
    if (!draft || !contact || props.readOnly) return;
    const savedRows = contact.followUps || [];
    if (savedRows.some(item=>item.id===draft.item.id)) {
      props.onUpdateFollowUps(contact.id,savedRows.filter(item=>item.id!==draft.item.id));
    }
    setDrafts(current=>{const next={...current};delete next[key];return next;});
  };

  return <section className="data-panel ax-followup-register">
    <header className="ax-followup-register__header">
      <div>
        <span className="section-kicker">CONNECTED CONTACT OPERATIONS</span>
        <h2>Follow-up Register</h2>
        <p>One editable register for every person, role, commitment and WhatsApp group linked through Contact 360.</p>
        <small>Edit any field below. Changes synchronize automatically when you leave the field, updating Contact 360 and the linked module record.</small>
      </div>
      <div className="ax-followup-register__actions">
        <button type="button" className="secondary-button" onClick={props.onExportPdf} disabled={!rows.length}><Download size={14}/> Download full PDF</button>
        <button type="button" className="secondary-button" onClick={()=>{document.body.classList.add("ax-print-followup-register");window.addEventListener("afterprint",()=>document.body.classList.remove("ax-print-followup-register"),{once:true});window.print();}}><FileText size={14}/> Print / Save as PDF</button>
      </div>
    </header>
    <div className="ax-followup-register__metrics">
      <div><span>Follow-up lines</span><strong>{rows.length}</strong></div>
      <div><span>Contacts involved</span><strong>{new Set(rows.map(row=>row.contact.id)).size}</strong></div>
      <div><span>Overdue reach-backs</span><strong>{overdueCount}</strong></div>
      <div><span>Primary module links</span><strong>{primaryCount}</strong></div>
      <div className="ax-followup-register__interest-metric"><span>Monthly interest receivable</span><strong>{formatINR(monthlyInterestReceivable)}</strong><small>Loans marked as interest receivable</small></div>
      <div className="ax-followup-register__interest-metric"><span>Monthly interest payable</span><strong>{formatINR(monthlyInterestPayable)}</strong><small>Loans marked as interest payable</small></div>
    </div>
    <div className="ax-followup-register__toolbar">
      <label className="ax-followup-register__search"><Search size={15}/><input type="search" value={query} onChange={event=>setQuery(event.target.value)} placeholder="Search contact, person, role, group, module, amount or description…"/></label>
      <label><span>Status</span><select value={statusFilter} onChange={event=>setStatusFilter(event.target.value)}><option>All statuses</option>{statuses.map(value=><option key={value}>{value}</option>)}</select></label>
      <label><span>Module type</span><select value={moduleFilter} onChange={event=>setModuleFilter(event.target.value)}><option>All modules</option>{moduleOptions.map(value=><option key={value}>{value}</option>)}</select></label>
      <label><span>Transaction</span><select value={transactionFilter} onChange={event=>setTransactionFilter(event.target.value)}><option>All transaction types</option>{transactionOptions.map(value=><option key={value}>{value}</option>)}</select></label>
      <label><span>Loan direction</span><select value={loanDirectionFilter} onChange={event=>setLoanDirectionFilter(event.target.value)}><option>All loan directions</option>{loanDirections.map(value=><option key={value}>{value}</option>)}</select></label>
      <details className="ax-followup-register__filter-dropdown"><summary>Roles{roleFilters.length?(` · ${roleFilters.length} selected`):" · All"}</summary><div className="ax-followup-register__filter-options">{roleOptions.map(role=><label key={role}><input type="checkbox" checked={roleFilters.includes(role)} onChange={event=>setRoleFilters(current=>event.target.checked?[...current,role]:current.filter(value=>value!==role))}/><span>{role}</span></label>)}{!roleOptions.length&&<small>No roles available</small>}</div></details>
      <details className="ax-followup-register__filter-dropdown"><summary><MessageCircle size={13}/> WhatsApp groups{groupFilters.length?(` · ${groupFilters.length} selected`):" · All"}</summary><div className="ax-followup-register__filter-options">{groupOptions.map(group=><label key={group.id}><input type="checkbox" checked={groupFilters.includes(group.id)} onChange={event=>setGroupFilters(current=>event.target.checked?[...current,group.id]:current.filter(value=>value!==group.id))}/><span>{group.name}</span></label>)}{!groupOptions.length&&<small>No linked WhatsApp groups</small>}</div></details>
      {(roleFilters.length>0||groupFilters.length>0)&&<button type="button" className="text-button" onClick={()=>{setRoleFilters([]);setGroupFilters([]);}}>Clear role / group filters</button>}
      <div className="ax-followup-register__add-contact">
        <label htmlFor="ax-followup-add-contact"><span>Add to contact</span></label>
        <div className="ax-followup-register__add-contact-search"><Search size={14}/><input id="ax-followup-add-contact" type="search" value={addContactSearch} onChange={event=>{setAddContactId("");setAddContactSearch(event.target.value);setAddContactPickerOpen(true);}} onFocus={()=>setAddContactPickerOpen(true)} onBlur={()=>setAddContactPickerOpen(false)} placeholder="Type a name, role or phone…"/>{addContactSearch&&<button type="button" onClick={()=>setAddContactSearch("")} aria-label="Clear contact search">×</button>}</div>
        {addContactPickerOpen&&<div className="ax-followup-register__add-contact-results">{matchingAddContacts.map(contact=><button type="button" key={contact.id} onMouseDown={event=>event.preventDefault()} onClick={()=>{setAddContactId(contact.id);setAddContactSearch(contact.name);setAddContactPickerOpen(false);}}><strong>{contact.name}</strong><small>{contact.role||"Contact"}{contact.phone?" · "+contact.phone:""}</small></button>)}{!matchingAddContacts.length&&<p>No saved contacts match this search.</p>}</div>}
      </div>
      <button type="button" className="primary-button" disabled={!addContactId||props.readOnly} onClick={()=>addForContact(addContactId)}><Plus size={14}/> Add follow-up</button>
    </div>
    <div className="ax-followup-register__result-line"><span>{visibleRows.length} of {rows.length} follow-up line(s)</span><span>Each person has a dedicated column. Their module assignments appear as separate editable cards.</span></div>
    <div className="ax-followup-register__summary-heading"><div><strong>People-wise follow-up overview</strong><span>Each person appears once. Every linked module record has its own editable description, amount, reach-back date and time.</span></div><span>{visibleByContact.size} person group(s) · {visibleRows.length} module / contact follow-up(s)</span></div>

    <div className="ax-followup-register__board" aria-label="Follow-up people columns">
    {Array.from(visibleByContact.entries()).map(([contactId,contactRows])=>{
      const contact = contactIndex.get(contactId);
      if(!contact)return null;
      const groups = Array.from(new Set(contactRows.flatMap(row=>row.groupNames)));
      const linkedRecordCount = new Set(contactRows.flatMap(row=>row.linkedRecords.map(record=>record.id))).size;
      return <article className="ax-followup-register__contact" key={contactId}>
        <header className="ax-followup-register__contact-head">
          <div className="ax-followup-register__avatar">{contact.name.split(/\s+/).map(part=>part[0]).join("").slice(0,2).toUpperCase()}</div>
          <div className="ax-followup-register__contact-meta">
            <strong>{contact.name}</strong>
            <span>{[contact.role,...(contact.roles||[]),contact.phone,contact.email].filter(Boolean).join(" · ")}</span>
            <small>{contactRows.length} follow-up commitment(s) · {linkedRecordCount} linked module record(s)</small>
            <div className="ax-followup-register__groups"><MessageCircle size={12}/>{groups.length?groups.map(group=><span key={group}>{group}</span>):<em>No WhatsApp groups linked</em>}</div>
          </div>
          <div className="ax-followup-register__contact-actions">
            <button type="button" className="secondary-button" onClick={()=>props.onOpenContact360(contactId)}><Users size={13}/> Contact 360</button>
            <button type="button" className="secondary-button" disabled={props.readOnly} onClick={()=>props.onAddModule(contactId)}><Plus size={13}/> Add module record</button>
            <button type="button" className="primary-button" disabled={props.readOnly} onClick={()=>addForContact(contactId)}><Plus size={13}/> Add follow-up</button>
          </div>
        </header>
        <div className="ax-followup-register__cards">
          {contactRows.map(row=>{
            const record = row.record;
            const item = row.item;
            return <article className="ax-followup-register__card" key={row.key}>
              <header className="ax-followup-register__card-head">
                <div className="ax-followup-register__card-module">
                  <span>{record?.module || "CONTACT-LEVEL FOLLOW-UP"}</span>
                  <strong>{record?.title || "New follow-up item"}</strong>
                  <small>{record ? (record.status || "Status not set") : "Link this item to a module record below"}</small>
                </div>
                <span className={"ax-followup-register__status ax-followup-register__status--"+item.status.toLowerCase().replace(/[^a-z0-9]+/g,"-")}>{item.status}</span>
              </header>
              <div className="ax-followup-register__card-fields">
                <label className="ax-followup-register__field ax-followup-register__field--wide">
                  <span>Module type / linked record</span>
                  <select aria-label="Linked module record" disabled={props.readOnly||Boolean(item.autoGenerated)} value={item.linkedRecordId} onChange={event=>chooseRecord(row.key,event.target.value)} onBlur={()=>save(row.key)}>
                    <option value="">Contact-level item</option>
                    {row.linkedRecords.map(linked=><option key={linked.id} value={linked.id}>{linked.module} · {linked.title}</option>)}
                  </select>
                  {item.autoGenerated&&<small>Created from this module's Follow-up Person assignment</small>}
                  {record&&<button type="button" className="ax-followup-register__inline-link" onClick={()=>props.onEditRecord(record)}><ExternalLink size={11}/> Open module record</button>}
                </label>
                <label className="ax-followup-register__field ax-followup-register__field--wide">
                  <span>Description / item</span>
                  <textarea aria-label="Follow-up description" rows={3} disabled={props.readOnly} value={item.description} onChange={event=>patch(row.key,"description",event.target.value)} onBlur={()=>save(row.key)} placeholder="What needs to be followed up? Add the exact task or commitment."/>
                </label>
                <label className="ax-followup-register__field">
                  <span>Amount (INR)</span>
                  <input aria-label="Follow-up amount" type="number" min="0" step="any" disabled={props.readOnly} value={item.amount} onChange={event=>patch(row.key,"amount",event.target.value)} onBlur={()=>save(row.key)} placeholder={record?.value||"0"}/>
                </label>
                <label className="ax-followup-register__field">
                  <span>Expected reach-back date</span>
                  <input aria-label="Expected reach-back date" type="date" disabled={props.readOnly} value={item.promisedDate} onChange={event=>patch(row.key,"promisedDate",event.target.value)} onBlur={()=>save(row.key)}/>
                </label>
                <label className="ax-followup-register__field">
                  <span>Expected reach-back time</span>
                  <input aria-label="Expected reach-back time" type="time" disabled={props.readOnly} value={item.promisedTime} onChange={event=>patch(row.key,"promisedTime",event.target.value)} onBlur={()=>save(row.key)}/>
                </label>
                <label className="ax-followup-register__field">
                  <span>Channel</span>
                  <select aria-label="Follow-up channel" disabled={props.readOnly} value={item.responseType} onChange={event=>patch(row.key,"responseType",event.target.value)} onBlur={()=>save(row.key)}>{channels.map(value=><option key={value}>{value}</option>)}</select>
                </label>
                <label className="ax-followup-register__field">
                  <span>Status</span>
                  <select aria-label="Follow-up status" disabled={props.readOnly} value={item.status} onChange={event=>patch(row.key,"status",event.target.value)} onBlur={()=>save(row.key)}>{statuses.map(value=><option key={value}>{value}</option>)}</select>
                </label>
                <label className="ax-followup-register__field ax-followup-register__field--wide">
                  <span>What the person said / outcome / next step</span>
                  <textarea aria-label="What the person said / terms" rows={2} disabled={props.readOnly} value={item.notes} onChange={event=>patch(row.key,"notes",event.target.value)} onBlur={()=>save(row.key)} placeholder="Record response, promise, outcome or next action."/>
                </label>
              </div>
              <footer className="ax-followup-register__card-actions">
                <label className="ax-followup-register__primary">
                  <input type="checkbox" checked={item.isPrimary} disabled={props.readOnly||Boolean(item.autoGenerated)||!item.linkedRecordId} onChange={event=>setPrimary(row.key,event.target.checked)}/>
                  <span>{item.isPrimary?"Primary module sync":"Independent follow-up"}</span>
                </label>
                <div className="ax-followup-register__row-actions">
                  <button type="button" className="primary-button" disabled={props.readOnly} onClick={()=>save(row.key)}><RefreshCw size={12}/> Save</button>
                  <button type="button" className="secondary-button" disabled={props.readOnly} onClick={()=>remove(row.key)} title="Remove follow-up line"><Trash2 size={13}/></button>
                  {record&&<button type="button" className="secondary-button" onClick={()=>props.onDownloadRecord(record)} title="Download linked record PDF"><Download size={13}/></button>}
                </div>
              </footer>
            </article>;
          })}
        </div>
      </article>;
    })}
    </div>
    {!visibleRows.length&&<div className="ax-followup-register__empty"><ClipboardList size={28}/><strong>{rows.length?"No follow-ups match these filters":"No follow-up lines have been recorded yet"}</strong><p>{rows.length?"Clear the search or filters to see the other saved commitments.":"Choose a contact above and add the first line. The same saved entry will appear in that person's Contact 360 workspace."}</p></div>}
    <p className="ax-followup-register__footnote">The board groups follow-ups by person. Add a module record directly from a person column or attach an existing linked record to a follow-up card. Date, time, description, channel, status and outcome are editable independently. Only the Primary assignment synchronizes its amount and response schedule into the linked module summary.</p>
  </section>;
}
