import { useEffect, useMemo, useState } from "react";
import {
  ArrowUpRight, Bookmark, CalendarClock, CalendarDays, ChevronRight,
  GitBranch, Landmark, Moon, Network, Sparkles, Sun, TrendingUp, Users, Wallet, Workflow
} from "lucide-react";
import IntelligenceHub from "./IntelligenceHub";
import { calculateMonthlyInterest, formatINR, parseDealNumber } from "./lib/deal-structure";

type FollowUp = {
  id:string; person:string; role:string; linkedRecordId:string; description:string; amount:string;
  promisedDate:string; promisedTime:string; responseType:string; status:string; notes:string;
  isPrimary:boolean; autoGenerated?:boolean; createdAt:string; updatedAt:string;
};
type RecordFollowUp = {
  id:string; followPersonId:string; followPersonName:string; followDate:string; followTime:string;
  remarks:string; nextFollowUpDate:string; nextFollowUpTime:string;
};
type ShiftProperty = {
  id:string; title:string; module:string; location:string; value:string; status:string; contact:string;
  primaryContactId?:string; followUpContactId?:string; targetDeadline?:string; targetDeadlineTime?:string;
  nextFollowUpDate?:string; nextFollowUpTime?:string; nextResponseDate?:string; nextResponseTime?:string;
  nextResponseDescription?:string; nextAction?:string; createdAt?:string; moduleData:Record<string,string>;
  followUpEntries?:RecordFollowUp[];
};
type ShiftContact = {id:string;name:string;phone:string;role:string;roles?:string[];followUps?:FollowUp[]};
type ShiftTask = {
  id:string;title:string;date:string;time:string;type:string;property:string;propertyId?:string;
  contactId?:string;contactName?:string;notes:string;done:boolean;
};
type ShiftFinancial = {
  id:string;propertyId?:string;contactId?:string;property:string;type:string;amount:string;
  date:string;party:string;reference:string;notes:string;
};
type FollowUpDraft = {
  contactId:string;linkedRecordId:string;description:string;amount:string;promisedDate:string;
  promisedTime:string;responseType:string;notes:string;status:string;
};
type ShiftSpace = "intent"|"timeline"|"connections"|"simulation"|"workflow";
type SavedView = {id:string;space:ShiftSpace;label:string;createdAt:string};
type TimelineEvent = {
  id:string;date:string;time:string;title:string;detail:string;kind:string;status:string;
  recordId?:string;contactId?:string;module?:string;
};
type Props = {
  properties:ShiftProperty[];contacts:ShiftContact[];tasks:ShiftTask[];financials:ShiftFinancial[];
  today:string;readOnly?:boolean;onOpenModule:(name:string)=>void;onOpenContacts:()=>void;
  onOpenTasks:()=>void;onOpenRecord:(id:string)=>void;onOpenContact:(id:string)=>void;
  onOpenFinancials:()=>void;onCreateFollowUp:(draft:FollowUpDraft)=>void;
  theme:"dark"|"light";onToggleTheme:()=>void;workspaceScope:string;
};
type SpaceDefinition = {id:ShiftSpace;label:string};
const SPACES:SpaceDefinition[]=[
  {id:"intent",label:"Intent Canvas"},
  {id:"timeline",label:"Temporal"},
  {id:"connections",label:"Relationships"},
  {id:"simulation",label:"Simulation"},
  {id:"workflow",label:"Mission workflow"}
];
const LOAN_MODULES=new Set(["Property Loans","Unsecured Company Loan","Personal Loan","Housing Loan"]);
const OPEN_STATUSES=new Set(["completed","closed","settled","rejected","cancelled","reached back"]);
const isOpen=(status:string)=>!OPEN_STATUSES.has(String(status||"").trim().toLowerCase());
const linkedToContact=(contact:ShiftContact,record:ShiftProperty)=>{
  const data=record.moduleData||{};
  const ids=[
    record.followUpContactId||"",record.primaryContactId||"",
    ...(data.__linkedContactIds||"").split(","),
    ...Object.entries(data).filter(([key,value])=>key.startsWith("__contact_")&&Boolean(value)).map(([,value])=>String(value))
  ].filter(Boolean);
  return ids.includes(contact.id)||(record.contact||"").trim().toLowerCase()===contact.name.trim().toLowerCase();
};
const loanRate=(record:ShiftProperty)=>parseDealNumber(record.moduleData?.__loanInterestRate||record.moduleData?.interestRate||record.moduleData?.annualInterestRate||"0");
const dateText=(value:string)=>value?new Date(value+"T00:00:00").toLocaleDateString("en-IN",{day:"2-digit",month:"short",year:"numeric"}):"No date";

export default function VestraShift(props:Props){
  const {
    properties,contacts,tasks,financials,today,readOnly=false,onOpenModule,onOpenContacts,
    onOpenTasks,onOpenRecord,onOpenContact,onOpenFinancials,onCreateFollowUp,
    theme,onToggleTheme,workspaceScope
  }=props;
  const [space,setSpace]=useState<ShiftSpace>("intent");
  const [timeFilter,setTimeFilter]=useState<"past"|"today"|"upcoming"|"all">("upcoming");
  const [selectedLoanId,setSelectedLoanId]=useState("");
  const [scenarioInput,setScenarioInput]=useState("");
  const contextKey="axivestra.vestraShift.views."+workspaceScope;
  const [savedViews,setSavedViews]=useState<SavedView[]>(()=>{
    try{const value=JSON.parse(window.localStorage.getItem(contextKey)||"[]");return Array.isArray(value)?value:[];}catch{return [];}
  });
  useEffect(()=>{try{window.localStorage.setItem(contextKey,JSON.stringify(savedViews));}catch{/* optional local preference */}},[contextKey,savedViews]);

  const loanRecords=useMemo(()=>properties.filter(record=>LOAN_MODULES.has(record.module)||record.moduleData?.__transactionType==="Loan"),[properties]);
  const selectedLoan=loanRecords.find(record=>record.id===selectedLoanId)||loanRecords[0];
  const method=selectedLoan?.moduleData?.__loanInterestMethod||(selectedLoan?.moduleData?.annualInterestRate?"Percentage per year":"Percentage per month");
  const currentRate=selectedLoan?loanRate(selectedLoan):0;
  const currentInterest=selectedLoan?calculateMonthlyInterest(selectedLoan.moduleData,parseDealNumber(selectedLoan.value)):0;
  const scenarioInterest=selectedLoan?calculateMonthlyInterest({...selectedLoan.moduleData,__loanInterestRate:scenarioInput||"0"},parseDealNumber(selectedLoan.value)):0;
  useEffect(()=>{if(selectedLoan)setScenarioInput(String(loanRate(selectedLoan)));},[selectedLoan?.id]);

  const timeline=useMemo<TimelineEvent[]>(()=>{
    const rows:TimelineEvent[]=[];
    const add=(event:TimelineEvent)=>{if(event.date&&/^\d{4}-\d{2}-\d{2}$/.test(event.date))rows.push(event);};
    tasks.forEach(task=>add({
      id:"task-"+task.id,date:task.date,time:task.time||"00:00",title:task.title,
      detail:[task.type,task.contactName,task.property,task.notes].filter(Boolean).join(" · "),
      kind:"Task",status:task.done?"Completed":task.date<today?"Overdue":"Scheduled",
      recordId:task.propertyId,contactId:task.contactId
    }));
    properties.forEach(record=>{
      if(record.targetDeadline)add({
        id:"deadline-"+record.id,date:record.targetDeadline,time:record.targetDeadlineTime||"09:00",
        title:"Target deadline · "+(record.title||record.module),detail:record.module+" · "+record.status,
        kind:"Deadline",status:record.targetDeadline<today?"Overdue":"Planned",recordId:record.id,module:record.module
      });
      if(record.nextFollowUpDate)add({
        id:"next-followup-"+record.id,date:record.nextFollowUpDate,time:record.nextFollowUpTime||"09:00",
        title:"Next follow-up · "+(record.title||record.module),detail:record.nextAction||record.module,
        kind:"Follow-up",status:record.nextFollowUpDate<today?"Overdue":"Scheduled",recordId:record.id,module:record.module
      });
      if(record.nextResponseDate)add({
        id:"response-"+record.id,date:record.nextResponseDate,time:record.nextResponseTime||"09:00",
        title:"Expected response · "+(record.title||record.module),
        detail:record.nextResponseDescription||record.nextAction||record.module,kind:"Response",
        status:record.nextResponseDate<today?"Overdue":"Expected",recordId:record.id,module:record.module
      });
      (record.followUpEntries||[]).forEach(entry=>{
        if(entry.followDate)add({
          id:"record-follow-"+entry.id,date:entry.followDate,time:entry.followTime||"09:00",
          title:"Record follow-up · "+(record.title||record.module),
          detail:[entry.followPersonName,entry.remarks].filter(Boolean).join(" · "),
          kind:"Follow-up",status:entry.followDate<today?"Overdue":"Recorded",recordId:record.id,module:record.module
        });
        if(entry.nextFollowUpDate)add({
          id:"record-next-"+entry.id,date:entry.nextFollowUpDate,time:entry.nextFollowUpTime||"09:00",
          title:"Next record follow-up · "+(record.title||record.module),
          detail:[entry.followPersonName,entry.remarks].filter(Boolean).join(" · "),
          kind:"Follow-up",status:entry.nextFollowUpDate<today?"Overdue":"Scheduled",recordId:record.id,module:record.module
        });
      });
    });
    contacts.forEach(contact=>(contact.followUps||[]).forEach(item=>{
      if(item.promisedDate)add({
        id:"commitment-"+item.id,date:item.promisedDate,time:item.promisedTime||"09:00",
        title:"Commitment · "+contact.name,
        detail:[item.description,item.amount,item.status].filter(Boolean).join(" · "),
        kind:"Commitment",status:item.promisedDate<today&&isOpen(item.status)?"Overdue":item.status||"Scheduled",
        contactId:contact.id,recordId:item.linkedRecordId||undefined,
        module:properties.find(record=>record.id===item.linkedRecordId)?.module
      });
    }));
    financials.forEach(item=>add({
      id:"financial-"+item.id,date:item.date,time:"12:00",
      title:item.type+" · "+(item.party||item.property||"Transaction"),
      detail:[item.amount,item.property,item.reference,item.notes].filter(Boolean).join(" · "),
      kind:"Financial",status:"Recorded",recordId:item.propertyId||undefined,contactId:item.contactId||undefined
    }));
    return rows.sort((a,b)=>(a.date+"T"+a.time).localeCompare(b.date+"T"+b.time));
  },[tasks,properties,contacts,financials,today]);
  const visibleTimeline=timeline.filter(event=>
    timeFilter==="all"||(timeFilter==="past"&&event.date<today)||
    (timeFilter==="today"&&event.date===today)||(timeFilter==="upcoming"&&event.date>today)
  );

  const connections=useMemo(()=>contacts.map(contact=>{
    const records=properties.filter(record=>linkedToContact(contact,record));
    const followUps=(contact.followUps||[]).filter(item=>isOpen(item.status));
    const linkedTasks=tasks.filter(task=>task.contactId===contact.id||records.some(record=>record.id===task.propertyId));
    return {contact,records,followUps,linkedTasks};
  }).filter(item=>item.records.length||item.followUps.length||item.linkedTasks.length)
    .sort((a,b)=>(b.records.length+b.followUps.length+b.linkedTasks.length)-(a.records.length+a.followUps.length+a.linkedTasks.length)),
  [contacts,properties,tasks]);

  const missions=useMemo(()=>[
    ...tasks.map(task=>({
      id:"task-"+task.id,title:task.title,
      detail:[task.property,task.contactName,task.type].filter(Boolean).join(" · "),
      date:task.date,status:task.done?"Completed":task.date<today?"Overdue":"In progress",
      recordId:task.propertyId,kind:"Task"
    })),
    ...properties.filter(record=>record.nextAction||record.targetDeadline||record.nextFollowUpDate).map(record=>({
      id:"record-"+record.id,title:record.title||record.module,
      detail:[record.module,record.nextAction||record.status].filter(Boolean).join(" · "),
      date:record.targetDeadline||record.nextFollowUpDate||"",
      status:record.status||"Open",recordId:record.id,kind:"Record"
    }))
  ].sort((a,b)=>(a.date||"9999-12-31").localeCompare(b.date||"9999-12-31")),
  [tasks,properties,today]);

  const saveView=()=>{
    const view:SavedView={id:"vs-"+Date.now(),space,label:SPACES.find(item=>item.id===space)?.label||"Workspace",createdAt:new Date().toISOString()};
    setSavedViews(current=>[view,...current].slice(0,8));
  };
  const openEvent=(event:TimelineEvent)=>{
    if(event.recordId){onOpenRecord(event.recordId);return;}
    if(event.contactId){onOpenContact(event.contactId);return;}
    if(event.kind==="Financial"){onOpenFinancials();return;}
    onOpenTasks();
  };

  return <section className="vs-shift" data-theme={theme}>
    <header className="vs-shift-hero">
      <div className="vs-shift-brand">
        <div className="vs-prism-emblem" aria-hidden="true"><i/><i/><i/><i/><i/></div>
        <div><span className="vs-eyebrow"><Sparkles size={13}/> VESTRA SHIFT · ADAPTIVE INTELLIGENCE OPERATING SYSTEM</span>
          <h2>Your workspace shifts with the work.</h2>
          <p>Assemble live information, explore relationships, inspect time and simulate decisions—without changing your saved records.</p>
        </div>
      </div>
      <div className="vs-hero-actions">
        <button type="button" className="vs-theme-toggle" onClick={onToggleTheme}>{theme==="dark"?<Sun size={15}/>:<Moon size={15}/>} {theme==="dark"?"Porcelain light":"Deep ink"} theme</button>
        <button type="button" onClick={onOpenTasks}><CalendarClock size={14}/> Schedule</button>
        <button type="button" className="vs-hero-primary" onClick={onOpenContacts}><Users size={14}/> People</button>
      </div>
    </header>

    <nav className="vs-shift-tabs" aria-label="VESTRA SHIFT workspaces">
      {SPACES.map(item=><button type="button" key={item.id} className={space===item.id?"active":""} aria-pressed={space===item.id} onClick={()=>setSpace(item.id)}>{item.label}</button>)}
      <button type="button" className="vs-save-context" onClick={saveView}><Bookmark size={13}/> Save workspace</button>
    </nav>
    {!!savedViews.length&&<div className="vs-saved-contexts"><span>YOUR SAVED WORKSPACES</span>{savedViews.map(view=><button type="button" key={view.id} onClick={()=>setSpace(view.space)}><Bookmark size={11}/>{view.label}</button>)}</div>}

    {space==="intent"&&<IntelligenceHub
      properties={properties} contacts={contacts} tasks={tasks} financials={financials}
      today={today} readOnly={readOnly} onOpenModule={onOpenModule} onOpenContacts={onOpenContacts}
      onOpenTasks={onOpenTasks} onCreateFollowUp={onCreateFollowUp}
    />}

    {space==="timeline"&&<section className="vs-space-page">
      <header><div><span className="vs-eyebrow">TEMPORAL WORKSPACE</span><h3>Past · present · upcoming</h3>
        <p>Only dates saved in tasks, record schedules, contact commitments and financial entries appear here.</p></div><CalendarDays size={22}/></header>
      <div className="vs-filter-row">{(["past","today","upcoming","all"] as const).map(value=><button type="button" key={value} className={timeFilter===value?"active":""} onClick={()=>setTimeFilter(value)}>{value==="all"?"All dates":value==="today"?"Today":value[0].toUpperCase()+value.slice(1)}</button>)}</div>
      <div className="vs-timeline-list">{visibleTimeline.map(event=><button type="button" key={event.id} className="vs-timeline-item" onClick={()=>openEvent(event)}>
        <span className={"vs-timeline-node "+(event.status==="Overdue"?"is-overdue":"")}/>
        <span className="vs-timeline-date">{dateText(event.date)}<small>{event.time}</small></span>
        <span className="vs-timeline-copy"><strong>{event.title}</strong><small>{event.detail||event.kind}</small></span>
        <span className="vs-event-status">{event.status}</span><ChevronRight size={15}/>
      </button>)}{!visibleTimeline.length&&<div className="vs-empty-state"><CalendarClock size={23}/><strong>No recorded events in this time window.</strong><small>Missing dates are not inferred.</small></div>}</div>
      <small className="vs-data-truth">Timeline uses saved timestamps only. It does not reconstruct missing historical events or mark planned work as completed.</small>
    </section>}

    {space==="connections"&&<section className="vs-space-page">
      <header><div><span className="vs-eyebrow">LIVING RECORDS · RELATIONSHIP INTELLIGENCE</span><h3>People connected to work</h3>
        <p>Connections are derived from saved contact IDs, linked contact fields, contact follow-ups and task assignments.</p></div><Network size={22}/></header>
      <div className="vs-relationship-grid">{connections.map(({contact,records,followUps,linkedTasks})=><article className="vs-relationship-card" key={contact.id}>
        <button type="button" className="vs-person-node" onClick={()=>onOpenContact(contact.id)}>
          <span className="vs-person-monogram">{contact.name.trim().split(/\s+/).slice(0,2).map(part=>part[0]||"").join("").toUpperCase()}</span>
          <span><strong>{contact.name}</strong><small>{contact.role||contact.roles?.join(", ")||"Contact"}</small></span><ChevronRight size={14}/>
        </button>
        <div className="vs-relationship-stats">
          <span><strong>{records.length}</strong><small>Records</small></span>
          <span><strong>{followUps.length}</strong><small>Open follow-ups</small></span>
          <span><strong>{linkedTasks.filter(task=>!task.done).length}</strong><small>Open tasks</small></span>
        </div>
        <div className="vs-related-records">{records.slice(0,5).map(record=><button type="button" key={record.id} onClick={()=>onOpenRecord(record.id)}>
          <span>{record.module}</span><strong>{record.title||"Untitled record"}</strong><small>{record.status||"Status not set"}</small>
        </button>)}{!records.length&&<small>Follow-up/task links exist, but no property record is linked.</small>}</div>
        <button type="button" className="vs-card-open" onClick={()=>onOpenContact(contact.id)}>Open Contact 360 <ArrowUpRight size={14}/></button>
      </article>)}{!connections.length&&<div className="vs-empty-state"><Users size={23}/><strong>No linked relationships to display.</strong><small>Links appear when saved records, follow-ups or tasks reference contacts.</small></div>}</div>
    </section>}

    {space==="simulation"&&<section className="vs-space-page vs-simulation-page">
      <header><div><span className="vs-eyebrow">PREDICTIVE SIMULATION STUDIO</span><h3>Test an interest-rate scenario</h3>
        <p>Adjust one input and compare the result with saved loan terms. The simulation never writes to a loan record.</p></div><TrendingUp size={22}/></header>
      {loanRecords.length?<>
        <label className="vs-loan-picker">Select a saved loan
          <select value={selectedLoan?.id||""} onChange={event=>{setSelectedLoanId(event.target.value);const next=loanRecords.find(record=>record.id===event.target.value);if(next)setScenarioInput(String(loanRate(next)));}}>
            {loanRecords.map(record=><option key={record.id} value={record.id}>{record.module} · {record.title||"Untitled loan"}</option>)}
          </select>
        </label>
        {selectedLoan&&<><div className="vs-simulation-inputs">
          <div><span>Principal from saved record</span><strong>{formatINR(parseDealNumber(selectedLoan.moduleData?.__loanPrincipal||selectedLoan.value))}</strong><small>{selectedLoan.moduleData?.__loanDirection||"Loan direction not set"}</small></div>
          <label>{method==="Fixed amount per month"?"Scenario interest amount per month (₹)":method==="Percentage per year"?"Scenario annual rate (%)":"Scenario monthly rate (%)"}
            <input type="number" min="0" step="0.01" value={scenarioInput} onChange={event=>setScenarioInput(event.target.value)}/>
            <small>Saved input: {currentRate}{method==="Fixed amount per month"?" ₹":" %"}</small>
          </label>
        </div>
        <div className="vs-simulation-results">
          <article><span>Current monthly interest</span><strong>{formatINR(currentInterest)}</strong><small>Calculated from saved loan terms</small></article>
          <article><span>Scenario monthly interest</span><strong>{formatINR(scenarioInterest)}</strong><small>Calculated from scenario input</small></article>
          <article className={scenarioInterest>currentInterest?"is-warning":"is-positive"}><span>Monthly difference</span><strong>{scenarioInterest-currentInterest>0?"+":""}{formatINR(scenarioInterest-currentInterest)}</strong><small>{scenarioInterest>currentInterest?"Increase":"Decrease or unchanged"} versus current terms</small></article>
        </div>
        <div className="vs-formula-note"><Landmark size={16}/><span><strong>Calculation method: {method}</strong><small>Uses AXIVESTRA's existing monthly-interest formula. This is a scenario, not a lender quote, verified balance or forecast.</small></span></div></>}
      </>:<div className="vs-empty-state"><Wallet size={23}/><strong>No saved loan records found.</strong><small>Add a loan in its existing module to activate interest scenarios.</small><button type="button" onClick={()=>onOpenModule("Property Loans")}>Open Property Loans <ArrowUpRight size={14}/></button></div>}
    </section>}

    {space==="workflow"&&<section className="vs-space-page">
      <header><div><span className="vs-eyebrow">MISSION WORKFLOWS</span><h3>Operational path and next actions</h3>
        <p>Tasks and record milestones are assembled from saved status, next-action and date fields.</p></div><Workflow size={22}/></header>
      <div className="vs-workflow-list">{missions.map((step,index)=><button type="button" key={step.id} className="vs-workflow-step" onClick={()=>step.recordId?onOpenRecord(step.recordId):onOpenTasks()}>
        <span className="vs-workflow-index">{String(index+1).padStart(2,"0")}</span><span className="vs-workflow-connector"/>
        <span className="vs-workflow-copy"><strong>{step.title}</strong><small>{step.detail||step.kind}</small></span>
        <span className="vs-workflow-date">{step.date?dateText(step.date):"No date"}<small>{step.status}</small></span><ChevronRight size={15}/>
      </button>)}{!missions.length&&<div className="vs-empty-state"><GitBranch size={23}/><strong>No active mission steps are recorded.</strong><small>Add a task or enter a next action/deadline on a saved record.</small></div>}</div>
      <button type="button" className="vs-open-schedule" onClick={onOpenTasks}>Open and manage tasks <ArrowUpRight size={14}/></button>
    </section>}
  </section>;
}
